use soda_ast::{DomainExpr, Module, ProofStep, Term};
use std::fmt::Write;

/// Generates `module()` using `soda-ast` constructors, including proof certificates.
pub fn emit_rust(module: &Module) -> String {
    let mut output = String::from("// Generated by SODA.\npub fn module() -> soda_ast::Module {\n");
    writeln!(
        output,
        "    soda_ast::Module {{ name: {:?}.into(),",
        module.name
    )
    .unwrap();
    writeln!(
        output,
        "        imports: vec![{}],",
        emit_strings(&module.imports)
    )
    .unwrap();
    output.push_str("        sorts: vec![\n");
    for sort in &module.sorts {
        writeln!(
            output,
            "            soda_ast::SortDecl {{ name: {:?}.into(), inductive: {} }},",
            sort.name, sort.inductive
        )
        .unwrap();
    }

    output.push_str("        ],\n        signatures: vec![\n");
    for signature in &module.signatures {
        writeln!(output, "            soda_ast::Signature {{ name: {:?}.into(), arguments: vec![{}], result: {:?}.into(), kind: soda_ast::SignatureKind::{:?} }},", signature.name, emit_strings(&signature.arguments), signature.result, signature.kind).unwrap();
    }

    output.push_str("        ],\n        records: vec![\n");
    for record in &module.records {
        let fields = record
            .fields
            .iter()
            .map(|(name, sort)| format!("({name:?}.into(), {sort:?}.into())"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(output, "            soda_ast::RecordDecl {{ name: {:?}.into(), constructor: {:?}.into(), fields: vec![{fields}] }},", record.name, record.constructor).unwrap();
    }
    output.push_str("        ],\n        monads: vec![\n");
    for monad in &module.monads {
        writeln!(output, "            soda_ast::MonadDecl {{ name: {:?}.into(), bind: {:?}.into(), unit: {:?}.into() }},", monad.name, monad.bind, monad.unit).unwrap();
    }

    output.push_str("        ],\n        judgments: vec![\n");
    for judgment in &module.judgments {
        writeln!(output, "            soda_ast::JudgmentDecl {{ name: {:?}.into(), arguments: vec![{}], kind: soda_ast::JudgmentKind::{:?} }},", judgment.name, emit_strings(&judgment.arguments), judgment.kind).unwrap();
    }

    output.push_str("        ],\n        notations: vec![\n");
    for notation in &module.notations {
        writeln!(output, "            soda_ast::NotationDecl {{ judgment: {:?}.into(), unicode: {:?}.into(), ascii: {:?}.into() }},", notation.judgment, notation.unicode, notation.ascii).unwrap();
    }

    output.push_str("        ],\n");
    output.push_str("        domains: vec![\n");
    for domain in &module.domains {
        let expression = match &domain.expression {
            DomainExpr::Flat(values) => {
                format!("soda_ast::DomainExpr::Flat(vec![{}])", emit_terms(values))
            }
            DomainExpr::Product(left, right) => {
                format!("soda_ast::DomainExpr::Product({left:?}.into(), {right:?}.into())")
            }
            DomainExpr::Function(left, right) => {
                format!("soda_ast::DomainExpr::Function({left:?}.into(), {right:?}.into())")
            }
            DomainExpr::Lifted(inner) => format!("soda_ast::DomainExpr::Lifted({inner:?}.into())"),
        };

        writeln!(
            output,
            "            soda_ast::DomainDecl {{ name: {:?}.into(), expression: {expression} }},",
            domain.name
        )
        .unwrap();
    }

    output.push_str("        ],\n        semantic_maps: vec![\n");
    for map in &module.semantic_maps {
        let entries = map
            .entries
            .iter()
            .map(|(key, value)| format!("({}, {})", emit_term(key), emit_term(value)))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(output, "            soda_ast::SemanticMap {{ name: {:?}.into(), input: {:?}.into(), output: {:?}.into(), entries: vec![{entries}] }},", map.name, map.input, map.output).unwrap();
    }

    writeln!(
        output,
        "        ],\n        fixed_points: vec![{}],\n        inductions: vec![",
        emit_strings(&module.fixed_points)
    )
    .unwrap();
    for induction in &module.inductions {
        writeln!(output, "            soda_ast::InductionProof {{ name: {:?}.into(), variable: {:?}.into(), sort: {:?}.into(), lhs: {}, rhs: {}, cases: vec![", induction.name, induction.variable, induction.sort, emit_term(&induction.lhs), emit_term(&induction.rhs)).unwrap();
        for case in &induction.cases {
            let steps = case
                .steps
                .iter()
                .map(emit_step)
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(output, "                soda_ast::InductionCase {{ constructor: {:?}.into(), arguments: vec![{}], steps: vec![{steps}] }},", case.constructor, emit_strings(&case.arguments)).unwrap();
        }

        output.push_str("            ] },\n");
    }

    output.push_str("        ],\n");
    output.push_str("        clause_details: vec![\n");
    for detail in &module.clause_details {
        let labels = detail
            .premise_labels
            .iter()
            .map(|label| {
                label
                    .as_ref()
                    .map_or_else(|| "None".into(), |name| format!("Some({name:?}.into())"))
            })
            .collect::<Vec<_>>()
            .join(", ");
        let bindings = detail
            .bindings
            .iter()
            .map(|binding| {
                format!(
                    "soda_ast::ComputedBinding {{ before_premise: {}, pattern: {}, value: {} }}",
                    binding.before_premise,
                    emit_term(&binding.pattern),
                    emit_term(&binding.value)
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(output, "            soda_ast::ClauseDetail {{ clause: {:?}.into(), premise_labels: vec![{labels}], bindings: vec![{bindings}], conditions: vec![{}] }},", detail.clause, emit_terms(&detail.conditions)).unwrap();
    }

    output.push_str("        ],\n");
    output.push_str("        rules: vec![\n");
    for rule in &module.rules {
        let condition = rule.condition.as_ref().map_or_else(
            || "None".into(),
            |term| format!("Some({})", emit_term(term)),
        );
        writeln!(
            output,
            "            soda_ast::Rule {{ name: {:?}.into(), lhs: {}, rhs: {}, condition: {} }},",
            rule.name,
            emit_term(&rule.lhs),
            emit_term(&rule.rhs),
            condition
        )
        .unwrap();
    }

    output.push_str("        ],\n        equations: vec![\n");
    for equation in &module.equations {
        writeln!(
            output,
            "            soda_ast::Equation {{ name: {:?}.into(), lhs: {}, rhs: {} }},",
            equation.name,
            emit_term(&equation.lhs),
            emit_term(&equation.rhs)
        )
        .unwrap();
    }

    output.push_str("        ],\n        proofs: vec![\n");
    for proof in &module.proofs {
        writeln!(
            output,
            "            soda_ast::Proof {{ name: {:?}.into(), lhs: {}, rhs: {}, steps: vec![",
            proof.name,
            emit_term(&proof.lhs),
            emit_term(&proof.rhs)
        )
        .unwrap();
        for step in &proof.steps {
            writeln!(output, "                {},", emit_step(step)).unwrap();
        }

        output.push_str("            ] },\n");
    }

    output.push_str("        ],\n        clauses: vec![\n");
    for clause in &module.clauses {
        writeln!(output, "            soda_ast::Clause {{ name: {:?}.into(), conclusion: {}, premises: vec![{}] }},", clause.name, emit_term(&clause.conclusion), emit_terms(&clause.premises)).unwrap();
    }

    writeln!(
        output,
        "        ],\n        evaluations: vec![{}],\n        queries: vec![{}],\n    }}\n}}",
        emit_terms(&module.evaluations),
        emit_terms(&module.queries)
    )
    .unwrap();

    output
}

fn emit_step(step: &ProofStep) -> String {
    let bindings = step
        .substitution
        .iter()
        .map(|(key, value)| format!("({key:?}.into(), {})", emit_term(value)))
        .collect::<Vec<_>>()
        .join(", ");

    format!(
        "soda_ast::ProofStep {{ axiom: {:?}.into(), reverse: {}, path: vec!{:?}, substitution: [{bindings}].into_iter().collect() }}",
        step.axiom, step.reverse, step.path
    )
}

fn emit_strings(strings: &[String]) -> String {
    strings
        .iter()
        .map(|value| format!("{value:?}.into()"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn emit_terms(terms: &[Term]) -> String {
    terms.iter().map(emit_term).collect::<Vec<_>>().join(", ")
}

fn emit_term(term: &Term) -> String {
    match term {
        Term::Var(name) => format!("soda_ast::Term::Var({name:?}.into())"),
        Term::Name(name) => format!("soda_ast::Term::Name({name:?}.into())"),
        Term::Binder {
            parameter,
            sort,
            body,
        } => format!(
            "soda_ast::Term::Binder {{ parameter: {parameter:?}.into(), sort: {sort:?}.into(), body: Box::new({}) }}",
            emit_term(body)
        ),
        Term::Int(value) => format!("soda_ast::Term::Int({value})"),
        Term::Bool(value) => format!("soda_ast::Term::Bool({value})"),
        Term::App(name, args) => {
            let args = emit_terms(args);

            format!("soda_ast::Term::App({name:?}.into(), vec![{args}])")
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escapes_rust_strings_and_preserves_integer_bounds() {
        let module = Module {
            name: "quoted\"\\\n".into(),
            evaluations: vec![Term::Int(i64::MIN), Term::Var("x".into())],
            ..Module::default()
        };
        let rust = emit_rust(&module);

        assert!(rust.contains("quoted\\\"\\\\\\n"));
        assert!(rust.contains("Term::Int(-9223372036854775808)"));
        assert!(rust.contains("Term::Var(\"x\".into())"));
    }
}
